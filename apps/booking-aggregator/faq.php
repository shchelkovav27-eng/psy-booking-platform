/* Приводим текст к виду, по которому ищем: без регистра, без ё и без знаков */
function faqNorm($s){
  $s = mb_strtolower(trim((string)$s));
  $s = str_replace(['ё', 'Ё'], 'е', $s);
  $s = preg_replace('/[^a-zа-я0-9\/ ]+/u', ' ', $s);
  return preg_replace('/\s+/u', ' ', $s);
}

/* Ищем подходящие ответы. Возвращаем список, лучший первым. */
function faqFind($question, $role = 'expert'){
  $q = faqNorm($question);
  if(mb_strlen($q) < 3) return [];
  $hits = [];
  foreach(FAQ($role) as $item){
    $score = 0;
    foreach($item['keys'] as $k){
      list($word, $weight) = $k;
      if(mb_strpos($q, faqNorm($word)) !== false) $score += $weight;
    }
    /* свой ответ важнее общего: куратору сначала про его кабинет */
    if($score > 0 && ($item['for'] ?? 'both') === $role) $score++;
    if($score > 0) $hits[] = ['score' => $score] + $item;
  }
  usort($hits, function($a, $b){ return $b['score'] - $a['score']; });
  return $hits;
}

function faqById($id, $role = 'expert'){
  foreach(FAQ($role) as $item) if($item['id'] === $id) return $item;
  return null;
}
